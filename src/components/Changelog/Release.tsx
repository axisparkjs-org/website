import React, { Fragment, type ReactNode } from 'react';
import Link from '@docusaurus/Link';
import Heading from '@theme/Heading';
import './changelog.css';

type Highlight = {
    title: string;
    summary: string;
    packages: string[];
};

type Props = {
    /** Anchor of the release, e.g. `v1.4.0`. */
    id: string;
    title: string;
    date?: string;
    /** `unreleased`, `major`, `minor` or `patch`: the size of the step in the timeline. */
    kind: 'unreleased' | 'major' | 'minor' | 'patch';
    docs?: string;
    api?: string;
    /** Benchmarks report of the release (src/pages/benchmarks/<version>.mdx), when it has been measured. */
    benchmarks?: string;
    latest?: boolean;
    highlights?: Highlight[];
    /** The full list of changes of the release, in markdown. */
    children: ReactNode;
};

// The entries are plain markdown for GitHub: show their code spans as code and drop the rest of the syntax.
function inline(text: string): ReactNode {
    return text
        .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
        .replace(/\*\*/g, '')
        .split(/(`[^`]+`)/)
        .map((part, index) => (index % 2 ? <code key={index}>{part.slice(1, -1)}</code> : <Fragment key={index}>{part}</Fragment>));
}

/**
 * One release of the changelog page (src/pages/changelog.mdx, generated by scripts/generate-changelog.mjs): a
 * step of the timeline with the version, its features as highlights and the full list of changes.
 */
export default function Release({ id, title, date, kind, docs, api, benchmarks, latest, highlights = [], children }: Props): ReactNode {
    return (
        <section className={`axc-release axc-release--${kind}${latest ? ' axc-release--latest' : ''}`}>
            <div className="axc-release__rail" aria-hidden="true">
                <span className="axc-release__node" />
            </div>

            <header className="axc-release__meta">
                <Heading as="h2" id={id} className="axc-release__version">
                    {title}
                </Heading>
                {latest && <span className="axc-release__badge">Latest</span>}
                {date && <p className="axc-release__date">{date}</p>}
                {(docs || api || benchmarks) && (
                    <p className="axc-release__links">
                        {docs && <Link to={docs}>Documentation</Link>}
                        {api && <Link to={api}>API reference</Link>}
                        {benchmarks && <Link to={benchmarks}>Benchmarks</Link>}
                    </p>
                )}
            </header>

            <div className="axc-release__content">
                {highlights.length > 0 && (
                    <ul className="axc-highlights">
                        {highlights.map((item) => (
                            <li key={item.title} className="axc-highlight glass">
                                <h3>{inline(item.title)}</h3>
                                <p>{inline(item.summary)}</p>
                                {item.packages.length > 0 && (
                                    <p className="axc-highlight__packages">
                                        {item.packages.map((name) => (
                                            <span key={name}>{name}</span>
                                        ))}
                                    </p>
                                )}
                            </li>
                        ))}
                    </ul>
                )}
                <div className="axc-details">
                    {highlights.length > 0 && <p className="axc-details__label">All changes</p>}
                    {children}
                </div>
            </div>
        </section>
    );
}
