import React, { useEffect, useState, type ReactNode } from 'react';
import Link from '@docusaurus/Link';
import useBaseUrl from '@docusaurus/useBaseUrl';
import LineChart from './LineChart';
import { environmentLabel } from './format';
import { METRICS, suiteCharts, type Metric } from './series';
import type { BenchData } from './types';
import './benchmarks.css';

interface Props {
    /** Package of the suites, e.g. `@axisparkjs/http-fastify`. */
    package: string;
    /** Only this suite (`http-fastify.requests`). Default: every suite of the package. */
    suite?: string;
    metric?: Metric;
}

/**
 * Evolution of the benchmarks of a package, to embed in its guide: `<BenchmarkChart package="@axisparkjs/http-fastify" />`.
 * It reads static/benchmarks/data.json (generated by scripts/generate-benchmarks.mjs) in the reference environment.
 */
export default function BenchmarkChart({ package: packageName, suite, metric = 'p50' }: Props): ReactNode {
    const url = useBaseUrl('/benchmarks/data.json');
    const [data, setData] = useState<BenchData | null | undefined>(undefined);

    useEffect(() => {
        let active = true;
        fetch(url)
            .then((response) => (response.ok ? response.json() : null))
            .then((json: BenchData | null) => active && setData(json))
            .catch(() => active && setData(null));
        return () => {
            active = false;
        };
    }, [url]);

    if (data === undefined) return <p className="axb-note">Loading the benchmarks…</p>;
    const environment = data?.environments[0]?.id;
    const charts = data && environment ? suiteCharts(data, environment, packageName, metric).filter((chart) => !suite || chart.suite === suite) : [];
    if (!data || charts.length === 0) return <p className="axb-note">There are no benchmarks of {packageName} yet.</p>;

    return (
        <div className="axb-embed">
            {charts.map((chart) => (
                <LineChart
                    key={chart.suite}
                    title={chart.suite}
                    subtitle={environmentLabel(environment as string)}
                    categories={data.releases}
                    series={chart.series}
                    format={METRICS[metric].format}
                    unit={METRICS[metric].unit}
                />
            ))}
            <p className="axb-note">
                <Link to="/benchmarks">All the benchmarks</Link>
            </p>
        </div>
    );
}
