#!/usr/bin/env node
// Saves the guides (docs/) and the generated API reference (api/) as a documentation version, so the site
// keeps the documentation of every release. Run by the CD after a release of axispark, with the released
// version: the documentation version is <major>.<minor>.
//
// - New minor (1.5.0): creates version 1.5 for both plugins; it becomes the default version of the site.
// - Patch of the latest minor (1.5.1): replaces version 1.5 with the current docs and API.
// - Patch of an older minor (1.4.3 when 1.5 exists): the current docs belong to a newer version, so nothing
//   is saved and the existing 1.4 snapshot is kept.
//
// Usage: node scripts/snapshot-version.mjs <released version>

import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const released = process.argv[2];
const match = released?.match(/^(\d+)\.(\d+)\.(\d+)$/);

if (!match) {
    console.error(`Usage: snapshot-version.mjs <major.minor.patch>, received "${released ?? ''}"`);
    process.exit(1);
}

const version = `${match[1]}.${match[2]}`;
const compare = (a, b) => {
    const [aMajor, aMinor] = a.split('.').map(Number);
    const [bMajor, bMinor] = b.split('.').map(Number);
    return aMajor - bMajor || aMinor - bMinor;
};

// Docs plugin "default" (guides) and "api" (API reference), see docusaurus.config.ts.
const plugins = [
    {
        command: 'docs:version',
        versionsFile: 'versions.json',
        docsDir: 'versioned_docs',
        sidebarsDir: 'versioned_sidebars'
    },
    {
        command: 'docs:version:api',
        versionsFile: 'api_versions.json',
        docsDir: 'api_versioned_docs',
        sidebarsDir: 'api_versioned_sidebars'
    }
];

const readVersions = (file) => (existsSync(join(root, file)) ? JSON.parse(readFileSync(join(root, file), 'utf8')) : []);
const [latest] = readVersions('versions.json');

if (latest && compare(version, latest) < 0) {
    console.log(`${released} is a patch of ${version}, older than the latest documented version ${latest}: no snapshot`);
    process.exit(0);
}

for (const plugin of plugins) {
    const versions = readVersions(plugin.versionsFile);

    // A patch release replaces the snapshot of its minor.
    if (versions.includes(version)) {
        rmSync(join(root, plugin.docsDir, `version-${version}`), {
            recursive: true,
            force: true
        });
        rmSync(join(root, plugin.sidebarsDir, `version-${version}-sidebars.json`), {
            force: true
        });
        writeFileSync(join(root, plugin.versionsFile), JSON.stringify(versions.filter((name) => name !== version)) + '\n');
    }

    execFileSync('npx', ['docusaurus', plugin.command, version], {
        cwd: root,
        stdio: 'inherit'
    });
}

// The sidebar generated by TypeDoc is not used (sidebars-api.ts is autogenerated) and has absolute paths.
rmSync(join(root, 'api_versioned_docs', `version-${version}`, 'typedoc-sidebar.cjs'), { force: true });

console.log(`Documentation version ${version} saved from ${released}`);
